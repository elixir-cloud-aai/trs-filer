"""Tests of the requirements of the image build (`scripts/image_requirements.py`)."""

import importlib.metadata
import importlib.util
from pathlib import Path
import re
import subprocess
import sys

import pytest

ROOT = Path(__file__).resolve().parents[1]
SCRIPT = ROOT / "scripts/image_requirements.py"

# `scripts/` is not a package, so the script is loaded from its file
_spec = importlib.util.spec_from_file_location("image_requirements", SCRIPT)
assert _spec and _spec.loader
image_requirements = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(image_requirements)

SHA = "db6998cae4e1f1fbbbaafd7a26795f3bbfa4511a"
PIN = f"foca @ git+https://github.com/elixir-cloud-aai/foca@{SHA}"
# Entries as `uv export` writes them: hashes and comments on continuation lines
HEADER = (
    "# This file was autogenerated by uv via the following command:\n"
    "#    uv export --frozen --no-dev --no-emit-project\n"
)
CONNEXION = (
    "connexion==2.15.1 \\\n"
    "    --hash=sha256:aaaa \\\n"
    "    --hash=sha256:bbbb\n"
    "    # via\n"
    "    #   trs-filer\n"
    "    #   foca\n"
)
GUNICORN = "gunicorn==26.2.0 \\\n    --hash=sha256:cccc\n    # via trs-filer\n"
FOCA_RELEASE = "foca==0.18.0 \\\n    --hash=sha256:dddd\n    # via trs-filer\n"
FOCA_COMMIT = f"{PIN}\n    # via trs-filer\n"


@pytest.mark.parametrize(
    "installed",
    [
        "0.16.1.dev7+gdb6998cae",
        "0.16.1.dev7+gdb6998c",
        "0.16.1.dev7+gdb6998cae.d20261022",
        f"0.16.1.dev7+g{SHA}",
    ],
)
def test_commit_pin(installed: str) -> None:
    """A pin of the base image's FOCA commit is left out, with its comments."""
    requirements = HEADER + CONNEXION + FOCA_COMMIT + GUNICORN
    assert image_requirements.image_requirements(requirements, installed) == (
        HEADER + CONNEXION + GUNICORN
    )


def test_release() -> None:
    """Locked FOCA releases are kept, with their hashes."""
    requirements = HEADER + CONNEXION + FOCA_RELEASE + GUNICORN
    assert image_requirements.image_requirements(requirements, "0.18.0") == (
        requirements
    )


@pytest.mark.parametrize("installed", ["0.18.1", "0.17.0", "0.18.0.dev1+gdb6998cae"])
def test_release_other_version(installed: str) -> None:
    """The build fails unless the base image has the locked FOCA release.

    Otherwise, the image would get another FOCA than its base image has
    (e.g., an update of the base image would be reverted by the lock).
    """
    with pytest.raises(
        ValueError, match=f"has FOCA {re.escape(installed)}, but 0.18.0 is locked"
    ):
        image_requirements.image_requirements(FOCA_RELEASE, installed)


@pytest.mark.parametrize(
    "requirement",
    [
        "foca==0.17.0 ; python_full_version >= '3.11' \\",
        "FOCA[x]==0.17.0 \\",
        "foca>=0.17.0 \\",
    ],
)
def test_release_other_form(requirement: str) -> None:
    """FOCA requirements other than a plain locked release are refused."""
    with pytest.raises(ValueError, match="must be locked as"):
        image_requirements.image_requirements(
            f"{requirement}\n    --hash=sha256:dddd\n", "0.18.0"
        )


def test_other_package() -> None:
    """Packages whose names start with `foca` aren't FOCA."""
    requirements = "foca-plugins==0.1.0 \\\n    --hash=sha256:eeee\n"
    assert image_requirements.image_requirements(requirements, "0.18.0") == (
        requirements
    )


def test_empty() -> None:
    """No requirements give no output."""
    assert image_requirements.image_requirements("", "0.18.0") == ""


def test_entries() -> None:
    """Continuation lines belong to the requirement above them."""
    assert image_requirements.entries("    # stray\n" + GUNICORN) == [
        ["    # stray"],
        ["gunicorn==26.2.0 \\", "    --hash=sha256:cccc", "    # via trs-filer"],
    ]


@pytest.mark.parametrize(
    "installed",
    ["0.17.0", "0.16.1.dev7+g0417848aa", "0.16.1.dev7+gdb699", "0.16.1+local"],
)
def test_other_commit(installed: str) -> None:
    """The build fails unless the base image has FOCA of the pinned commit."""
    with pytest.raises(
        ValueError, match=f"has FOCA {re.escape(installed)}, not of commit"
    ):
        image_requirements.image_requirements(FOCA_COMMIT, installed)


@pytest.mark.parametrize(
    "dependency",
    [
        "foca @ git+https://github.com/elixir-cloud-aai/foca@dev",
        "foca @ git+https://github.com/example/foca@" + SHA,
        "foca[x] @ https://example.org/foca.tar.gz",
        "FOCA@https://example.org/foca.tar.gz",
    ],
)
def test_other_reference(dependency: str) -> None:
    """Direct references of FOCA other than to a commit are refused."""
    with pytest.raises(ValueError, match="full commit SHA"):
        image_requirements.image_requirements(
            f"{dependency}\n", "0.16.1.dev7+gdb6998cae"
        )


def test_main(
    tmp_path: Path,
    capsys: pytest.CaptureFixture[str],
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """`main()` prints the requirements, or the error, for FOCA's version."""
    monkeypatch.setattr(importlib.metadata, "version", {"foca": "0.18.0"}.__getitem__)
    requirements = tmp_path / "requirements.txt"
    requirements.write_text(FOCA_RELEASE + GUNICORN)
    assert image_requirements.main([str(requirements)]) == 0
    assert capsys.readouterr().out == FOCA_RELEASE + GUNICORN
    requirements.write_text(FOCA_COMMIT)
    assert image_requirements.main([str(requirements)]) == 1
    assert capsys.readouterr().err == (
        f"error: The base image has FOCA 0.18.0, not of commit {SHA}\n"
    )


def test_script(tmp_path: Path) -> None:
    """The script runs as the image build calls it."""
    requirements = tmp_path / "requirements.txt"
    requirements.write_text(GUNICORN)
    result = subprocess.run(  # noqa: S603 (fixed arguments, no shell)
        [sys.executable, "-I", str(SCRIPT), str(requirements)],
        capture_output=True,
        text=True,
        cwd=tmp_path,
        check=False,
    )
    assert (result.returncode, result.stdout, result.stderr) == (0, GUNICORN, "")
